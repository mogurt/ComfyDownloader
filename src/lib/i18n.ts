type TranslationKey = keyof typeof translations.en;
type Params = Record<string, string | number>;

function interpolate(template: string, params?: Params) {
  if (!params) return template;
  return template.replace(/\{\{(\w+)\}\}/g, (_, key) => String(params[key] ?? ""));
}

export function translateWithLanguage(
  language: AppLanguage,
  key: TranslationKey,
  params?: Params
) {
  const template = translations[language][key] ?? translations.en[key] ?? key;
  return interpolate(template, params);
}

export function translate(key: TranslationKey, params?: Params) {
  const language = useSettingsStore.getState().settings.language;
  return translateWithLanguage(language, key, params);
}

export function useI18n() {
  const language = useSettingsStore((s) => s.settings.language);

  const t = useMemo(
    () => (key: TranslationKey, params?: Params) =>
      translateWithLanguage(language, key, params),
    [language]
  );

  return { language, t };
}

